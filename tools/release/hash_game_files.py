#!/usr/bin/env python3
"""Write src/mgr_game_manifest.inc from an extracted copy of the supported disc.

The manifest lists every file the game reads (default.xex and media/) with its
size and XXH3-64, so the app can verify a player's disc image while installing
it. Only hashes are recorded, never game data.

    python3 tools/release/hash_game_files.py private/game src/mgr_game_manifest.inc
"""
import argparse
import pathlib
import sys

import xxhash

CHUNK = 1 << 20
SKIP_NAMES = {".DS_Store"}


def game_files(root: pathlib.Path):
    yield root / "default.xex"
    media = root / "media"
    if not media.is_dir():
        sys.exit(f"{media} is not a directory")
    for path in sorted(media.rglob("*")):
        if path.is_file() and path.name not in SKIP_NAMES:
            yield path


def file_hash(path: pathlib.Path) -> int:
    h = xxhash.xxh3_64()
    with path.open("rb") as f:
        while chunk := f.read(CHUNK):
            h.update(chunk)
    return h.intdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("game_root", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()

    if not (args.game_root / "default.xex").is_file():
        sys.exit(f"{args.game_root} has no default.xex")
    lines = [
        "// Generated by tools/release/hash_game_files.py. Do not edit.",
        "// {path relative to the game root, size in bytes, XXH3-64}",
    ]
    for path in game_files(args.game_root):
        rel = path.relative_to(args.game_root).as_posix()
        if '"' in rel or "\\" in rel:
            sys.exit(f"unsupported file name: {rel}")
        lines.append(f'{{"{rel}", {path.stat().st_size}ull, 0x{file_hash(path):016x}ull}},')
        print(rel, file=sys.stderr)
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
