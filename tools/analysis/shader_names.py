"""Name the shaders the GPU received, for MGR_SHADER_NAMES effect attribution.

Maps every shader in Xenia's shader storage (.xsh) to the XDK shader containers
it came from. Pixel shaders are keyed by their ucode hash; vertex shaders by the
hash with bit 63 set (how depth-only draws are tagged). Vertex shaders whose
fetch instructions were patched at bind time have no exact container: they get
the closest one prefixed with "~".

usage: shader_names.py <4B4E080A.xsh> <shader container dir> <out.tsv>
"""
import os
import struct
import sys

from ucode_match import container_ucode, read_xsh

VERTEX_SHADER_TAG_BIT = 1 << 63
MIN_NEAR_SCORE = 0.5  # fraction of same-position words for a "~" name


def load_containers(root_dir):
    containers = []
    for root, _, files in os.walk(root_dir):
        for name in sorted(files):
            try:
                stage, code = container_ucode(open(os.path.join(root, name), "rb").read())
            except (struct.error, ValueError):
                continue
            label = os.path.basename(root) + "/" + os.path.splitext(name)[0]
            containers.append((stage, code, label))
    return containers


def nearest(stage, code, containers):
    words = struct.unpack(f">{len(code) // 4}I", code)
    best_score, best_label = 0.0, None
    for other_stage, other, label in containers:
        if other_stage != stage:
            continue
        other_words = struct.unpack(f">{len(other) // 4}I", other)
        same = sum(1 for a, b in zip(words, other_words) if a == b)
        score = same / max(len(words), len(other_words))
        if score > best_score:
            best_score, best_label = score, label
    return best_label if best_score >= MIN_NEAR_SCORE else None


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    stored = read_xsh(sys.argv[1])
    containers = load_containers(sys.argv[2])
    by_code = {}
    for stage, code, label in containers:
        by_code.setdefault(code, []).append(label)
    exact = near = 0
    with open(sys.argv[3], "w") as out:
        out.write("# hash\tname (generated by tools/analysis/shader_names.py)\n")
        for shader_hash, is_pixel, code in stored:
            stage = "ps" if is_pixel else "vs"
            labels = by_code.get(code)
            if labels:
                exact += 1
                name = "|".join(sorted(set(labels)))
            else:
                label = nearest(stage, code, containers)
                if not label:
                    continue
                near += 1
                name = "~" + label
            tag = shader_hash if is_pixel else shader_hash | VERTEX_SHADER_TAG_BIT
            out.write(f"{tag:016X}\t{stage}:{name}\n")
    print(f"{len(stored)} stored shaders: {exact} exact, {near} nearest, "
          f"{len(stored) - exact - near} unnamed")


if __name__ == "__main__":
    main()
