"""Write the X-macro list of D3D-library functions wrapped by src/mgr_d3d_census.cpp.

Functions that MGR already overrides elsewhere are left out, because a second
strong definition would not link.

usage: gen_d3d_census.py generated/default src > src/mgr_d3d_census_list.inc
"""
import glob
import re
import sys

D3D_START, D3D_END = 0x826A0000, 0x826D0000
DEFINE = re.compile(r"^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)", re.M)
OVERRIDE = re.compile(r"REX_FUNC\(sub_([0-9A-F]{8})\)|MGR_D3D_WRAP\(([0-9A-F]{8})\)")
CENSUS_SOURCE = "mgr_d3d_census"


def main():
    generated, sources = sys.argv[1], sys.argv[2]
    defined = set()
    for path in glob.glob(f"{generated}/*.cpp"):
        defined.update(DEFINE.findall(open(path).read()))
    overridden = set()
    for path in glob.glob(f"{sources}/**/*.cpp", recursive=True):
        if CENSUS_SOURCE in path:
            continue
        for a, b in OVERRIDE.findall(open(path).read()):
            overridden.add(a or b)
    wrapped = sorted(a for a in defined
                     if D3D_START <= int(a, 16) < D3D_END and a not in overridden)
    print("// Generated by tools/analysis/gen_d3d_census.py. Do not edit.")
    print(f"// {len(wrapped)} D3D-library functions; {len(overridden)} overridden elsewhere are skipped.")
    print("#define MGR_D3D_CENSUS_LIST(X) \\")
    for i in range(0, len(wrapped), 6):
        print("  " + " ".join(f"X({a})" for a in wrapped[i:i + 6]) + " \\")
    print()


if __name__ == "__main__":
    main()
